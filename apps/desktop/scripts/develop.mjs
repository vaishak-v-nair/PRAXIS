import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { reviewSources } from '../../../src/lib/review-install.js';
const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), checkout = path.resolve(desktop, '../..');
const runtime = path.join(desktop, '.build', 'dev-runtime');
fs.mkdirSync(runtime, { recursive: true });
fs.copyFileSync(path.join(checkout, 'src/lib/review-service.js'), path.join(runtime, 'review-service.mjs'));
fs.copyFileSync(path.join(checkout, 'src/lib/review-service-runtime.js'), path.join(runtime, 'review-service-runtime.mjs'));
fs.copyFileSync(path.join(desktop, 'runtime/supervisor.mjs'), path.join(runtime, 'supervisor.mjs'));
const version = JSON.parse(fs.readFileSync(path.join(desktop, 'package.json'))).version;
const runtimeId = reviewSources().fingerprint;
fs.writeFileSync(path.join(runtime, 'manifest.json'), JSON.stringify({ schema: 'praxis.desktop-runtime.v1', mode: 'source', version, runtimeId, appPath: path.join(checkout, 'apps/workbench') }));
const required = [path.join(checkout, 'apps/workbench/.next/BUILD_ID'), path.join(checkout, 'apps/workbench/.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python')];
if (required.some(file => !fs.existsSync(file))) throw new Error('Build Workbench and install its Python environment before desktop development. See apps/desktop/README.md.');
const cli = path.join(desktop, 'node_modules/@tauri-apps/cli/tauri.js');
const child = spawn(process.execPath, [cli, 'dev', ...process.argv.slice(2)], { cwd: desktop, env: { ...process.env, PRAXIS_DESKTOP_RUNTIME: runtime, PRAXIS_DESKTOP_NODE: process.execPath }, windowsHide: true, stdio: 'inherit', shell: false });
child.once('exit', code => { process.exitCode = code ?? 1; });
child.once('error', error => { console.error(error.message); process.exitCode = 1; });
